SLOTS=['08:30','11:30','14:30','17:30','20:30']
def main():
    have={os.path.basename(f)[:-5]:json.load(open(f))['publishedAt'] for f in glob.glob('content/posts/*.json')}
    used=collections.defaultdict(set)
    for t in have.values():
        if t>='2026-11-15': used[t[:10]].add(t[11:16])
    days=[]; d=datetime.date(2026,11,15)
    while d<=datetime.date(2026,12,31): days.append(d); d+=datetime.timedelta(1)
    todo=[t for t in TOPICS if t[0] not in have]
    assert len({t[0] for t in TOPICS})==len(TOPICS),'trung slug'
    pools={k:[t for t in todo if t[4]==k] for k in ('','noel','tet','cuoinam')}
    out=[]
    for d in days:
        free=[s for s in SLOTS if s not in used[d.isoformat()]][:max(0,5-len(used[d.isoformat()]))]
        for s in free:
            if d<=datetime.date(2026,12,14) and pools['noel'] and d>=datetime.date(2026,11,18) and len([o for o in out if o['ngay']==d.isoformat() and o['mua']=='noel'])<1: k='noel'
            elif d>=datetime.date(2026,12,8) and pools['tet'] and len([o for o in out if o['ngay']==d.isoformat() and o['mua']=='tet'])<1: k='tet'
            elif datetime.date(2026,11,25)<=d<=datetime.date(2026,12,28) and pools['cuoinam'] and len([o for o in out if o['ngay']==d.isoformat() and o['mua']=='cuoinam'])<1 and d.day%3==0: k='cuoinam'
            else: k=''
            if not pools[k]: k=next((x for x in ('','tet','cuoinam','noel') if pools[x]),None)
            if k is None: break
            # luân phiên danh mục: lấy chủ đề đầu tiên khác danh mục bài liền trước
            prev=out[-1]['cat'] if out else ''
            i=next((j for j,t in enumerate(pools[k]) if t[1]!=prev),0)
            t=pools[k].pop(i)
            out.append({'ngay':d.isoformat(),'gio':s,'slug':t[0],'cat':t[1],'kw':t[2],'goc':t[3],'mua':t[4]})
    json.dump(out,open('tools/viet-bai/lich-5-bai-ngay.json','w'),ensure_ascii=False,indent=1)
    left=sum(len(v) for v in pools.values())
    print('xep',len(out),'con thua',left,'chu de',len(TOPICS))
if __name__=='__main__': main()
